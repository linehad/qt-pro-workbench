const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const vscode = require("vscode");

exports.activate = async function () {
    const report = { passed: false, errors: [], comparisons: [] };
    const reportFile = path.join(__dirname, "../git-history-results.json");
    const save = () => fs.writeFileSync(reportFile, JSON.stringify(report, null, 4));
    const waitForTab = async label => {
        for (let attempt = 0; attempt < 30; ++attempt) {
            if (vscode.window.tabGroups.all.some(group => group.tabs.some(tab => tab.label === label))) { return; }
            await new Promise(resolve => setTimeout(resolve, 100));
        }
        throw new Error(`Tab did not open: ${label}`);
    };
    try {
        assert(!vscode.workspace.workspaceFolders?.length);
        const sessionId = vscode.env.sessionId;
        report.fixture = fs.mkdtempSync(path.join(__dirname, "../git-history-vscode-"));
        const git = (cwd, ...args) => execFileSync("git", ["-C", cwd, "-c", "core.autocrlf=false", "-c", "user.name=VS Code QA", "-c", "user.email=qa@example.invalid", ...args], { encoding: "utf8", windowsHide: true });
        const work = path.join(report.fixture, "work"); const main = path.join(report.fixture, "main");
        for (const root of [work, main]) { fs.mkdirSync(root); git(root, "init", "--quiet"); }
        const commit = (root, subject) => { git(root, "add", "--all"); git(root, "commit", "--quiet", "-m", subject); return git(root, "rev-parse", "HEAD").trim(); };
        const project = path.join(work, "App.pro"); const source = path.join(work, "main.cpp");
        fs.writeFileSync(project, "SOURCES = main.cpp\n"); fs.writeFileSync(source, "int value = 1;\n"); commit(work, "first");
        fs.writeFileSync(source, "int value = 2;\n"); const latest = commit(work, "changed");
        const cmake = path.join(main, "CMakeLists.txt"); fs.writeFileSync(cmake, "cmake_minimum_required(VERSION 3.20)\nproject(QA LANGUAGES CXX)\nadd_executable(QA main.cpp)\n");
        fs.writeFileSync(path.join(main, "main.cpp"), "int value = 90;\n"); commit(main, "main only");
        const extension = vscode.extensions.getExtension("ynlim.qt-pro-workbench");
        report.version = extension.packageJSON.version; assert.equal(report.version, "0.12.12");
        const api = await extension.activate(); const call = (operation, args = {}) => api.execute({ operation, arguments: args });
        assert((await vscode.commands.getCommands()).includes("qtPro.showFileGitHistory"));
        await call("qt_select_project", { projectPath: cmake }); await call("qt_select_project", { projectPath: project });
        const initial = await call("qt_get_state");
        const document = await vscode.workspace.openTextDocument(source);
        const edit = new vscode.WorkspaceEdit(); edit.insert(document.uri, document.positionAt(document.getText().length), "// unsaved QA\n"); await vscode.workspace.applyEdit(edit);
        await vscode.window.showTextDocument(document);
        const dirtyText = document.getText();
        report.graph = await vscode.commands.executeCommand("qtPro.showGitHistory", { kind: "project", projectPath: project });
        assert.equal(report.graph.repositoryRoot.toLowerCase(), work.toLowerCase());
        report.otherGraph = await call("qt_git_show_graph", { projectPath: cmake });
        assert.equal(report.otherGraph.repositoryRoot.toLowerCase(), main.toLowerCase());
        const page = await call("qt_git_history", { file: source, limit: 1 });
        assert.equal(page.commits[0].hash, latest); assert.equal(page.hasMore, true);
        const older = await call("qt_git_history", { file: source, skip: page.nextSkip });
        assert.equal(older.commits[0].subject, "first");
        report.read = await call("qt_git_read_revision", { file: source, revision: latest, historicalPath: page.commits[0].filePath });
        assert.equal(report.read.text, "int value = 2;\n");
        const other = await call("qt_git_history", { file: path.join(main, "main.cpp") });
        assert.equal(other.commits[0].subject, "main only");
        const log = await vscode.commands.executeCommand("qtPro.showFileGitHistory", vscode.Uri.file(source));
        assert.equal(log.opened, true); assert.equal(log.repositoryRoot.toLowerCase(), work.toLowerCase());
        await new Promise(resolve => setTimeout(resolve, 800));
        const logTabs = () => vscode.window.tabGroups.all.flatMap(group => group.tabs).filter(tab => tab.label === "Git 이력 조회 · main.cpp");
        assert.equal(logTabs().length, 1); assert(logTabs()[0].input instanceof vscode.TabInputWebview);
        await call("qt_git_show_file_history", { file: source }); assert.equal(logTabs().length, 1);
        report.persistentHistoryTab = true;
        const firstDiff = await call("qt_git_open_diff", { file: source, revision: latest }); report.comparisons.push(firstDiff); save();
        assert.equal((await vscode.workspace.openTextDocument(vscode.Uri.parse(firstDiff.left))).getText(), "int value = 1;\n");
        assert.equal((await vscode.workspace.openTextDocument(vscode.Uri.parse(firstDiff.right))).getText(), "int value = 2;\n");
        assert(vscode.window.tabGroups.activeTabGroup.activeTab.input instanceof vscode.TabInputTextDiff);
        assert.equal(logTabs().length, 1);
        const workingDiff = await call("qt_git_open_diff", { file: source, revision: latest, comparison: "working" }); report.comparisons.push(workingDiff);
        assert.equal(vscode.Uri.parse(workingDiff.right).fsPath.toLowerCase(), source.toLowerCase());
        const latestDiff = await vscode.commands.executeCommand("qtPro.compareLatestGitRevision", vscode.Uri.file(source));
        assert.equal(latestDiff.revision, latest); assert.equal((await vscode.workspace.openTextDocument(vscode.Uri.parse(latestDiff.right))).getText(), dirtyText);
        const driver = path.join(work, "driver"); fs.mkdirSync(driver); fs.mkdirSync(path.join(driver, "sub"));
        const legacy = path.join(driver, "legacy.cpp"); const nested = path.join(driver, "sub", "nested.h");
        const driverPart = path.join(driver, "Driver.pri");
        const koreanBytes = Buffer.from("2f2f20c7d1b1db20c1d6bcae208c630d0a", "hex");
        fs.writeFileSync(legacy, Buffer.concat([Buffer.from("int value = 1;\r\n"), koreanBytes]));
        fs.writeFileSync(nested, "// nested source\n"); fs.writeFileSync(driverPart, "SOURCES = legacy.cpp\n"); commit(work, "legacy Korean source");
        fs.writeFileSync(legacy, Buffer.concat([Buffer.from("int value = 2;\r\n"), koreanBytes]));
        fs.writeFileSync(nested, "// updated nested source\n"); fs.writeFileSync(driverPart, "SOURCES = legacy.cpp sub/nested.h\n"); const koreanHash = commit(work, "three driver files");
        const driverPage = await call("qt_git_history", { file: driver });
        assert.equal(driverPage.directoryPath, "driver"); assert.equal(driverPage.commits[0].hash, koreanHash);
        assert.deepEqual(driverPage.commits[0].changes.map(change => change.filePath), ["driver/Driver.pri", "driver/legacy.cpp", "driver/sub/nested.h"]);
        assert.equal(driverPage.commits.length, 2);
        await vscode.commands.executeCommand("qtPro.showFileGitHistory", { kind: "folder", projectPath: project, directoryPath: driver });
        await waitForTab("Git 이력 조회 · driver");
        assert(vscode.window.tabGroups.all.some(group => group.tabs.some(tab => tab.label === "Git 이력 조회 · driver")));
        const includeLog = await vscode.commands.executeCommand("qtPro.showFileGitHistory", { kind: "include", projectPath: project, partPath: driverPart, label: "Driver" });
        assert.equal(includeLog.file.toLowerCase(), driver.toLowerCase());
        const partLog = await vscode.commands.executeCommand("qtPro.showFileGitHistory", { kind: "file", projectPath: project, partPath: driverPart, filePath: driverPart, label: "Driver.pri" });
        assert.equal(partLog.file.toLowerCase(), driverPart.toLowerCase()); report.includeFolderHistory = true;
        const koreanDiff = await call("qt_git_open_diff", { file: legacy, revision: koreanHash });
        assert.equal((await vscode.workspace.openTextDocument(vscode.Uri.parse(koreanDiff.left))).getText(), "int value = 1;\r\n// 한글 주석 똠\r\n");
        assert.equal((await vscode.workspace.openTextDocument(vscode.Uri.parse(koreanDiff.right))).getText(), "int value = 2;\r\n// 한글 주석 똠\r\n");
        fs.appendFileSync(legacy, "// local change\r\n");
        const legacyLocal = await call("qt_git_compare_latest", { file: legacy });
        const legacyDocument = await vscode.workspace.openTextDocument(vscode.Uri.parse(legacyLocal.right));
        assert.equal(legacyDocument.getText(), "int value = 2;\r\n// 한글 주석 똠\r\n// local change\r\n");
        assert.equal(legacyDocument.encoding, "euckr");
        await vscode.workspace.openTextDocument(legacyDocument.uri, { encoding: "utf8" });
        assert(!legacyDocument.getText().includes("똠"));
        await call("qt_git_compare_latest", { file: legacy });
        assert.equal(legacyDocument.encoding, "euckr"); assert(legacyDocument.getText().includes("똠"));
        report.koreanEncoding = legacyDocument.encoding; report.directoryHistory = driverPage.commits.length; report.latestDiff = true;
        await call("qt_git_open_revision", { file: source, revision: latest });
        assert.equal(vscode.window.activeTextEditor.document.uri.scheme, "qt-pro-git");
        assert.equal(vscode.window.activeTextEditor.document.getText(), "int value = 2;\n");
        const state = await call("qt_get_state"); report.workspace = state.workspace;
        assert.deepEqual(state.workspace, []); assert.equal(vscode.env.sessionId, sessionId);
        assert.equal(state.activeProject, initial.activeProject); assert.equal(state.configuration, initial.configuration); assert.equal(state.kitId, initial.kitId);
        assert.equal(document.getText(), dirtyText); assert.equal(document.isDirty, true); assert.equal(fs.readFileSync(source, "utf8"), "int value = 2;\n");
        assert.deepEqual(report.errors, []);
        const inactiveClosed = await call("qt_close_project", { projectPath: cmake });
        assert.equal(inactiveClosed.activeProject, initial.activeProject); assert.equal(inactiveClosed.projects.length, 1);
        const lastClosed = await call("qt_close_project", { projectPath: project });
        assert.equal(lastClosed.activeProject, undefined); assert.deepEqual(lastClosed.projects, []);
        assert.equal(document.isDirty, true); assert.equal(document.getText(), dirtyText);
        assert.equal(fs.readFileSync(project, "utf8"), "SOURCES = main.cpp\n");
        report.closedProjects = [cmake, project];
        report.passed = true; save();
        await vscode.window.showTextDocument(document); await vscode.commands.executeCommand("workbench.action.files.revert");
        await vscode.commands.executeCommand("workbench.action.closeWindow");
    } catch (error) { report.error = error.stack || String(error); save(); }
};
