const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { TXProjectParser } = require("../out/XProjectParser");
const { TXIntelliSenseProjects } = require("../out/XIntelliSenseProjects");
const { referenceProjects, referenceFiles } = require("../out/XReferenceScope");

test("references include open projects in the source repository, exclude identical symbols in another root and closed projects, and names search all opened projects", t => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), "reference-scope-"));
    t.after(() => fs.rmSync(root, { recursive: true, force: true }));
    const write = (file, text = "") => { const target = path.join(root, file); fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, text); return target; };
    write("work/.git", "gitdir: fixture"); write("main/.git", "gitdir: fixture");
    const driver = write("work/driver/driver.pro", "SOURCES += Fins.cpp\n");
    const first = write("work/driver/Fins.cpp", "void same() {}\n");
    const other = write("work/other/other.pro", "SOURCES += Other.cpp\n");
    const call = write("work/other/Other.cpp", "void same(); void use() { same(); }\n");
    const copy = write("main/driver/driver.pro", "SOURCES += Fins.cpp\n");
    const duplicate = write("main/driver/Fins.cpp", "void same() {}\n");
    const closed = write("work/closed/closed.pro", "SOURCES += Closed.cpp\n");
    const closedFile = write("work/closed/Closed.cpp", "void same() {}\n");
    const getProject = project => new TXProjectParser().parse(project);
    const projects = referenceProjects([driver, other, copy], getProject);
    const workFiles = referenceFiles(projects, first);
    assert(workFiles.has(first.toLowerCase())); assert(workFiles.has(call.toLowerCase()));
    assert(!workFiles.has(duplicate.toLowerCase())); assert(!workFiles.has(closedFile.toLowerCase()));
    const mainFiles = referenceFiles(projects, duplicate);
    assert(mainFiles.has(duplicate.toLowerCase())); assert(!mainFiles.has(first.toLowerCase()));
    assert(referenceFiles(projects).has(duplicate.toLowerCase()));
    const index = new TXIntelliSenseProjects({ projects: () => [driver, other, copy], getProject, preferences: () => ({ configuration: "debug" }), kits: () => [], activeProject: () => driver, storagePath: root, reportError: error => { throw error; } });
    index.refresh();
    assert(index.browseConfiguration(path.join(root, "work")).browsePath.includes(call.toLowerCase()));
    assert(!index.browseConfiguration(path.join(root, "work")).browsePath.includes(duplicate.toLowerCase()));
    assert(index.browseConfiguration(root).browsePath.includes(call.toLowerCase()));
    assert(index.browseConfiguration(root).browsePath.includes(duplicate.toLowerCase()));
    assert(!index.browseConfiguration().browsePath.includes(closedFile.toLowerCase()));
    assert.equal(index.configurationFor(closedFile), undefined);
    assert(!referenceFiles(projects, closedFile).size);
});
